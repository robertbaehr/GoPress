// Package porting generates PORTING.md from the php-reference tree.
package porting

import (
	"bufio"
	"fmt"
	"os"
	"os/exec"
	"path"
	"sort"
	"strings"
)

// WriteStatus walks every *.php file at ref and writes PORTING.md.
func WriteStatus(outPath, mapPath, ref string) error {
	rules, err := loadMap(mapPath)
	if err != nil {
		return err
	}
	files, err := listPHP(ref)
	if err != nil {
		return err
	}
	sort.Strings(files)

	f, err := os.Create(outPath)
	if err != nil {
		return err
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "# GoPress PORTING status\n\n")
	fmt.Fprintf(w, "Generated by `gopress-tools porting-status` against `%s`.\n\n", ref)
	fmt.Fprintf(w, "| PHP path | Go target | status | task | API |\n")
	fmt.Fprintf(w, "|---|---|---|---|---|\n")

	missing := 0
	for _, php := range files {
		target, status, task, api := match(rules, php)
		if target == "" && status == "" {
			missing++
			status = "todo"
			target = guessTarget(php)
			task = ""
			api = "n/a"
		}
		if status == "" {
			status = "todo"
		}
		if api == "" {
			api = "n/a"
		}
		fmt.Fprintf(w, "| `%s` | `%s` | %s | %s | %s |\n", php, target, status, task, api)
	}
	if err := w.Flush(); err != nil {
		return err
	}
	if missing > 0 {
		// Still write the file; CI in later revisions can fail hard.
		fmt.Fprintf(os.Stderr, "porting-status: %d files used guessed targets (no explicit map rule)\n", missing)
	}
	return nil
}

type rule struct {
	Prefix string
	Go     string
	Status string
	Task   string
	API    string
}

func loadMap(path string) ([]rule, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var rules []rule
	var cur rule
	flush := func() {
		if cur.Prefix != "" {
			rules = append(rules, cur)
			cur = rule{}
		}
	}
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "- prefix:") {
			flush()
			cur.Prefix = strings.Trim(strings.TrimSpace(strings.TrimPrefix(line, "- prefix:")), `"'`)
			continue
		}
		if strings.HasPrefix(line, "go:") {
			cur.Go = strings.Trim(strings.TrimSpace(strings.TrimPrefix(line, "go:")), `"'`)
		} else if strings.HasPrefix(line, "status:") {
			cur.Status = strings.Trim(strings.TrimSpace(strings.TrimPrefix(line, "status:")), `"'`)
		} else if strings.HasPrefix(line, "task:") {
			cur.Task = strings.Trim(strings.TrimSpace(strings.TrimPrefix(line, "task:")), `"'`)
		} else if strings.HasPrefix(line, "api:") {
			cur.API = strings.Trim(strings.TrimSpace(strings.TrimPrefix(line, "api:")), `"'`)
		}
	}
	flush()
	// Longest prefix first.
	sort.Slice(rules, func(i, j int) bool {
		return len(rules[i].Prefix) > len(rules[j].Prefix)
	})
	return rules, nil
}

func match(rules []rule, php string) (goTarget, status, task, api string) {
	for _, r := range rules {
		if r.Prefix == php || strings.HasPrefix(php, r.Prefix) {
			return r.Go, r.Status, r.Task, r.API
		}
	}
	return "", "", "", ""
}

func guessTarget(php string) string {
	switch {
	case strings.HasPrefix(php, "wp-admin/"):
		return "internal/admin"
	case strings.HasPrefix(php, "wp-includes/rest-api/"):
		return "internal/rest"
	case strings.HasPrefix(php, "wp-includes/blocks/"):
		return "internal/blocks/library"
	case strings.HasPrefix(php, "wp-includes/block-supports/"):
		return "internal/blocks/supports"
	case strings.HasPrefix(php, "wp-includes/html-api/"):
		return "internal/htmlapi"
	case strings.HasPrefix(php, "wp-includes/"):
		base := strings.TrimPrefix(php, "wp-includes/")
		base = strings.TrimSuffix(base, ".php")
		base = strings.ReplaceAll(base, "-", "_")
		base = strings.ReplaceAll(base, "/", "_")
		base = strings.TrimPrefix(base, "class_wp_")
		return "internal/wp/" + base + ".go"
	case php == "wp-login.php":
		return "internal/login"
	case php == "wp-cron.php":
		return "internal/wp/cron.go"
	case php == "index.php" || php == "wp-blog-header.php" || php == "wp-load.php" || php == "wp-settings.php":
		return "internal/server"
	default:
		return "internal/wp"
	}
}

func listPHP(ref string) ([]string, error) {
	cmd := exec.Command("git", "ls-tree", "-r", "--name-only", ref)
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-tree %s: %w", ref, err)
	}
	var files []string
	for _, line := range strings.Split(string(out), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || !strings.HasSuffix(line, ".php") {
			continue
		}
		// Normalize.
		files = append(files, path.Clean(line))
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no php files at %s", ref)
	}
	return files, nil
}
